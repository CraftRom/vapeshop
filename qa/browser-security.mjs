// Real browser + real API; fixtures only replace Telegram and PostgreSQL.
import { chromium } from 'playwright'
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH, args: ['--no-sandbox'] } : {}) })
const base = 'http://127.0.0.1:5176'
let checks = 0
function check(ok, label) { checks++; console.log(`${ok ? 'PASS' : 'FAIL'} ${label}`); if (!ok) throw new Error(label) }
try {
 const context = await browser.newContext()
 const page = await context.newPage()
 const errors=[];page.on('pageerror',err=>errors.push(err.message))
 await page.goto(base+'/login')
 await page.getByRole('button',{name:'Увійти',exact:true}).waitFor()
 await page.getByLabel('Логін',{exact:true}).fill('admin')
 await page.getByLabel('Пароль',{exact:true}).fill('secret')
 const response = page.waitForResponse(r=>r.url().endsWith('/auth/browser-login'))
 await page.getByRole('button',{name:'Увійти',exact:true}).click()
 const login = await response
 check(login.status()===200 && !(await login.json()).access_token,'browser login returns no bearer token')
 await page.waitForURL(base+'/')
 check(await page.evaluate(()=>!sessionStorage.getItem('shop_dashboard_token')&&!localStorage.getItem('shop_dashboard_token')),'auth token absent from Web Storage')
 const cookies=await context.cookies(base)
 check(cookies.some(c=>c.name==='shop_dev_session'&&c.httpOnly&&c.sameSite==='Strict'),'development session uses HttpOnly SameSite cookie')
 check(!await page.evaluate(()=>document.cookie.includes('shop_dev_session')),'JavaScript cannot read cookie')
 await page.goto(base+'/catalog')
 await page.getByRole('heading',{name:'Каталог',exact:true}).waitFor()
 await page.reload()
 await page.getByRole('heading',{name:'Каталог',exact:true}).waitFor()
 check(page.url().endsWith('/catalog'),'reload restores server session')
 const noCsrf=await page.evaluate(async()=>{const r=await fetch('/api/catalog/categories',{method:'POST',headers:{'Content-Type':'application/json','X-Dashboard-Request':'1'},body:JSON.stringify({name:'attacker'})});return r.status})
 check(noCsrf===403,'browser POST without CSRF rejected by API')
 await page.locator('.catalog-categories-btn').click()
 await page.getByRole('button',{name:'Нова категорія',exact:true}).click()
 const modal=page.getByRole('dialog',{name:'Нова категорія',exact:true})
 await modal.getByLabel('Назва групи',{exact:true}).fill('Cookie QA')
 const writeResponse=page.waitForResponse(r=>r.url().endsWith('/catalog/categories')&&r.request().method()==='POST')
 await modal.getByRole('button',{name:'Зберегти',exact:true}).click()
 const write=await writeResponse
 check(write.status()===201 && Boolean(write.request().headers()['x-csrf-token']),'dashboard UI writes through CSRF protected session')
 await modal.waitFor({state:'hidden'})
 await page.getByRole('dialog',{name:'Категорії та субкатегорії',exact:true}).locator('footer').getByRole('button',{name:'Закрити',exact:true}).click()
 const stolen = cookies.find(c=>c.name==='shop_dev_session')
 await page.getByRole('button',{name:'Вийти',exact:true}).first().click()
 await page.waitForURL(base+'/login')
 check(!(await context.cookies(base)).some(c=>c.name==='shop_dev_session'),'logout removes cookie after API revocation')
 await context.addCookies([stolen])
 const replay=await context.request.get(base+'/api/auth/session')
 check(replay.status()===401,'stolen logged-out cookie cannot be replayed')
 await page.reload()
 await page.getByRole('button',{name:'Увійти',exact:true}).waitFor()
 check(page.url().endsWith('/login'),'expired or revoked session returns login')
 check(errors.length===0,'no browser runtime errors '+errors.join('; '))
 console.log(`REAL SESSION BROWSER: ${checks}/${checks}`)
 await context.close()
} finally { await browser.close() }
