def describe(code: str) -> Event:
    """Опис події. Невідомий код теж отримує опис, а не порожнечу.

    Код, якого немає в каталозі, — це майже завжди свій же виклик із
    друкарською помилкою. Мовчазна відсутність опису означала б, що подія
    є, але в панелі вона виглядає порожнім рядком, і ніхто не зрозуміє,
    що саме зламалося.
    """
    known = CATALOG.get(code)
    if known:
        return known
    return Event(code, "notice", code,
                 "Подія без опису в каталозі. Швидше за все, код указано "
                 "з помилкою або забули додати його в security_log.CATALOG.")


def record(code: str, /, **fields) -> None:
    """Записує подію безпеки.

    Викликається зсередини обробників, тож не має права нічого зламати:
    невдале логування безпеки не повинно перетворювати робочий запит на
    помилку. Тому все загорнуто в try.
    """
    try:
        event = describe(code)
        level = logging.WARNING if event.severity == "alarm" else logging.INFO
        log.log(
            level,
            event.title,
            extra={
                "event": event.code,
                "severity": event.severity,
                "detail": event.detail,
                "security": True,
                **fields,
            },
        )
    except Exception:  # pragma: no cover
        pass


class OnlySecurity(logging.Filter):
    """Пропускає лише записи журналу безпеки."""

    def filter(self, record: logging.LogRecord) -> bool:
        return getattr(record, "security", False) is True


def attach(directory: Path) -> None:
    """Підключає окремий файл security.log.

    Копій зберігаємо вдвічі більше, ніж у звичайних журналів. Подій тут на
    порядки менше, тож ті самі мегабайти зберігають місяці замість днів —
    а розбір інциденту нерідко починається через тиждень після нього.
    """
    from shop.logging_setup import JsonFormatter, log_backups, log_max_bytes

    handler = logging.handlers.RotatingFileHandler(
        directory / "security.log",
        maxBytes=log_max_bytes(),
        backupCount=log_backups() * 2,
        encoding="utf-8",
    )
    handler.setFormatter(JsonFormatter("security"))
    handler.addFilter(OnlySecurity())
    logging.getLogger("security").addHandler(handler)

    # Записи безпеки йдуть і в спільний журнал теж — там вони губляться
    # серед тисяч запитів, зате видно поруч із помилкою, яка сталася в ту
    # саму секунду. Дублювання тут корисне, тож propagate лишаємо.
