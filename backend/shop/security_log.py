"""Журнал безпеки: окремий потік подій про доступ.

Навіщо окремо, а не рівнем у спільному файлі. Події безпеки трапляються
рідко — кілька за добу проти тисяч запитів. У спільному файлі вони тонуть:
щоб знайти вчорашню невдалу спробу входу, довелося б переглянути десятки
тисяч рядків про завантаження каталогу. І навпаки: спільний файл
прокручується за дні, а журнал безпеки при тому самому розмірі зберігає
місяці — саме тоді, коли розбір інциденту починається через тиждень після
події.

Друга причина — доступ. Спільний журнал бачить лише системний
адміністратор, бо в ньому шляхи запитів, тіла помилок і внутрішні
подробиці. Журнал безпеки за змістом вужчий і потрібен частіше.

Кожна подія описана в каталозі нижче, а не складається з рядка на місці
виклику. Це не формальність. Коли подія лишається просто текстом,
однакові речі поступово починають писатися по-різному — «невдалий вхід»,
«помилка входу», «login failed», — і відфільтрувати їх разом стає
неможливо. Каталог дає фіксовану назву для фільтра, людський опис для
того, хто дивиться в панель, і рівень критичності для вирішення, чи
будити цим адміністратора.
"""
