# вхід нічого не ламає, але знати про нього треба.
SEVERITIES = ("info", "notice", "alarm")

# Від якого рівня надсилаємо в канал. Нижче цього — лише у файл: успішні
# входи й вихід із панелі трапляються десятки разів на день, і канал, у
# якому вони, ніхто не читатиме.
ALERT_FROM = "notice"


