"""Повідомлення клієнту про зміну статусу замовлення.

Раніше на більшість статусів ішов один рядок: «статус змінено на
«Оплачене»». Формально правда, практично марно — клієнт не дізнавався ні
що відбулося, ні що робити далі, ні коли чекати посилку. Кожне таке
повідомлення породжувало питання менеджеру, тобто економія на тексті
оберталася витратою людського часу.

Тут кожен статус пояснює три речі: що сталося, що буде далі й чи потрібна
дія від клієнта. Графік відправок береться з відповіді FAQ, щоб він
змінювався в одному місці.
"""
from __future__ import annotations

from shop.entities import Order, OrderStatus


def _money(value, currency: str) -> str:
    return f"{value:.0f} {currency}"


def compose(order: Order, status: OrderStatus, shop) -> str | None:
    """Текст для клієнта або None, якщо про цей статус повідомляє інший код.

    None для «Прийняте в роботу» і «Відправлене» — у них власні
    повідомлення з іменем менеджера й номером накладної відповідно.
    Дублювати їх тут означало б надсилати по два повідомлення поспіль.
    """
    currency = getattr(shop, "currency", "грн")
    number = f"№{order.id}"

    if status == OrderStatus.CONFIRMED:
        return (
            f"📋 <b>Замовлення {number} підтверджено</b>\n\n"
            f"Сума: <b>{_money(order.total, currency)}</b>\n\n"
            "Товар зарезервовано за вами. Менеджер звʼяжеться найближчим "
            "часом, щоб узгодити доставку.\n\n"
            "<i>Відправки: будні 11:00–12:00 і 18:00–19:00, "
            "вихідні 16:00–17:00.</i>"
        )

    if status == OrderStatus.PAID:
        return (
            f"💚 <b>Оплату отримано</b>\n\n"
            f"Замовлення {number} на <b>{_money(order.total, currency)}</b> "
            "оплачено повністю.\n\n"
            "Далі — пакування й відправка. Щойно посилка поїде, надішлемо "
            "номер накладної для відстеження.\n\n"
            "<i>Замовлення, підтверджені до 18:00 у будні та до 16:00 "
            "у вихідні, їдуть того ж дня.</i>"
        )

    if status == OrderStatus.DONE:
        return (
            f"🎉 <b>Замовлення {number} виконано</b>\n\n"
            "Дякуємо, що обрали нас. Сподіваємось, усе сподобалось.\n\n"
            "Якщо з товаром щось не так — напишіть у чат замовлення, "
            "розберемось. Гарантія діє й після отримання."
        )

    if status == OrderStatus.CANCELLED:
        parts = [
            f"❌ <b>Замовлення {number} скасовано</b>\n",
            "Товар повернувся в наявність.",
        ]
        # Про бонуси кажемо лише коли вони справді були: рядок «бонуси
        # повернуто: 0» виглядає як помилка й породжує зайве питання.
        if order.bonus_used and order.bonus_used > 0:
            parts.append(
                f"Списані бонуси повернуто на рахунок: "
                f"<b>{_money(order.bonus_used, currency)}</b>."
            )
        parts.append(
            "\nЯкщо скасування сталося помилково — просто оформіть "
            "замовлення знову або напишіть менеджеру."
        )
        return "\n".join(parts)

    if status == OrderStatus.NEW:
        # Повернення в «Нове» — рідкість, але воно буває при виправленні
        # помилки менеджера. Мовчати тут гірше, ніж сказати просто.
        return (
            f"↩️ <b>Замовлення {number} повернуто в обробку</b>\n\n"
            "Менеджер уточнює деталі. Ми напишемо, щойно все буде готово."
        )

    return None
