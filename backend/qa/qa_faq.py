"""Розпізнавання питань: збіги, межі, вимкнені модулі."""
import os
os.environ.update(BOT_TOKEN="1:t", JWT_SECRET="t"*32)
from bot import faq

fails=[]
def check(c,l,d=""):
    print(f"  {'✓' if c else '✗'} {l}"+("" if c else f" — {d}")); (None if c else fails.append(l))

CASES = [
    ("Де замовити?", "order"), ("як замовити", "order"), ("Де купити", "order"),
    ("як купити ?", "order"), ("Як оформити замовлення", "order"),
    ("хочу заказать", "order"), ("где купить", "order"),
    ("скільки коштує", "price"), ("Ціна яка?", "price"), ("почому", "price"),
    ("як доставка працює", "delivery"), ("відправляєте новою поштою?", "delivery"),
    ("як оплатити", "payment"), ("накладений платіж є?", "payment"),
    ("Де моє замовлення", "status"), ("дайте ттн", "status"), ("коли прийде", "status"),
    ("можна повернути?", "returns"), ("товар бракований", "returns"), ("гарантія є", "returns"),
    ("з якого віку", "age"), ("мені 18 можна?", "age"),
    ("є промокод?", "promo"), ("які знижки", "promo"),
    ("що з бонусами", "bonus"), ("реферальна програма", "referral"),
    ("опт цікавить", "wholesale"), ("як звʼязатися з менеджером", "contacts"),
    ("який графік роботи", "hours"), ("Привіт", "greeting"), ("дякую!", "thanks"),
    ("Що є в наявності", "catalog"),
]
print("--- розпізнавання ---")
for text, expected in CASES:
    got = faq.match(text)
    check(got and got.key == expected, f"«{text}» → {expected}", got and got.key)

print("\n--- бот мовчить, коли не впевнений ---")
for text in ["Відділення 12", "+380671112233", "Шевченко Тарас Григорович",
             "ок", "", "   ", "3 шт", "Іван"]:
    check(faq.match(text) is None, f"без відповіді: «{text}»", faq.match(text) and faq.match(text).key)

print("\n--- вимкнені модулі ---")
class Shop:
    bonus_enabled=False; referral_enabled=False; min_age=21
    bonus_max_percent=30; referral_percent=5; currency="грн"
check(faq.match("бонуси", Shop()) is None, "про бонуси мовчимо, коли модуль вимкнено")
check(faq.match("реферальна програма", Shop()) is None, "про рефералів так само")
class On(Shop):
    bonus_enabled=True; referral_enabled=True
check(faq.match("бонуси", On()).key == "bonus", "з увімкненим модулем відповідає")

print("\n--- підстановка даних ---")
r = faq.match("з якого віку", Shop())
check("21" in faq.render(r, Shop()), "вік береться з налаштувань", faq.render(r, Shop()))
r = faq.match("бонуси", On())
check("30" in faq.render(r, On()), "ліміт бонусів підставлено", faq.render(r, On()))

print("\n--- нормалізація ---")
check(faq.match("ЯК ЗАМОВИТИ???") is not None, "регістр і знаки")
check(faq.match("як   замовити") is not None, "зайві пробіли")
check(faq.match("🛍 як замовити") is not None, "емодзі на початку")

import pathlib
print("\n--- як пишуть насправді ---")
# Люди не пишуть «яка вартість доставки». Вони пишуть «скільки за пересил»,
# «почім», «а дешевше можна». Кожен рядок нижче — форма, яку бот раніше
# або не розпізнавав, або відносив не до того правила.
LIVE = {
    "cancel": ("хочу скасувати замовлення", "передумав, не потрібно",
               "відмініть будь ласка", "не буду брати", "анулюйте замовлення",
               "отмените заказ"),
    "genuine": ("це оригінал чи підробка?", "не паль?", "чи є сертифікат",
                "у вас оригінал?", "качество нормальное?"),
    "returns": ("не тягне взагалі", "мигає і не заряджається",
                "протікає", "прийшов розбитий", "смак горілий",
                "прислали не те", "не включається"),
    "promo": ("можна дешевше?", "для постійних клієнтів знижка є?",
              "промокод є?", "скиньте ціну"),
    "price": ("скільки коштує", "почім", "яка сума вийде"),
    # «Коли прийде» свідомо лишається за правилом статусу: так питає той,
    # у кого замовлення вже є, а відповідь про статус веде його туди, де
    # видно накладну. Новачок питає інакше — «скільки йде доставка».
    "delivery": ("скільки йде доставка", "новою поштою відправляєте?",
                 # «Скільки коштує пересилка» лишається за правилом ціни: обидва
    # відповіді ведуть у магазин, а розводити їх довелося б словом
    # «пересилка» проти «коштує» — надто тонко, щоб бути надійним.
    "самовивіз є?", "скільки йде посилка"),
    "status": ("де моє замовлення", "дайте ттн", "вже відправили?"),
}
for key, samples in LIVE.items():
    for said in samples:
        got = faq.match(said)
        if not got or got.key != key:
            fails.append(f"«{said}» → {got.key if got else 'нічого'}, а мало {key}")

print("\n--- «оплачено» — не питання про оплату ---")
# Зі знімка: людина написала «Оплачено», а бот пояснив їй, ЯК платити.
# Слово збігалося з правилом про оплату за коренем «оплат». Розрізняє не
# тема, а форма дієслова: доконаний вид означає дію, яка вже сталася.
from bot.faq import payment_claim                                    # noqa: E402

for said in ("Оплачено", "я сплатив", "Оплатив, чек скинув", "переказав 750",
             "Скинула квитанцію", "оплата пройшла", "деньги отправил",
             "щойно оплатив", "вже оплатив", "ось чек", "гроші пішли",
             "оплата прошла", "деньги ушли", "готово, оплатив"):
    if not payment_claim(said): fails.append(f"«{said}» мало б бути повідомленням про оплату")

for asked in ("як оплатити?", "куди скинути гроші", "чи можна оплатити карткою",
              "як я можу оплатити", "скільки коштує доставка", "привіт",
              # Найпідступніше: коротке «чек» збігалося з «чекати», і
              # людина, яка питає про строки, отримувала відповідь про переказ.
              "чекаю доставку", "я чекав тиждень", "скільки ще чекати"):
    if payment_claim(asked): fails.append(f"«{asked}» мало б лишитись питанням")

# Ціна помилки різна в різні боки, і це навмисно: прийняти питання за
# повідомлення про оплату — менеджер прочитає зайве; навпаки — людина
# отримає інструкцію замість підтвердження й піде писати ще раз.
_chat = pathlib.Path("bot/handlers/chat.py").read_text()
if "claims_payment = faq.payment_claim" not in _chat: fails.append("обробник перевіряє намір до довідки")
if "not quoted and not claims_payment" not in _chat: fails.append("довідка такі повідомлення не перехоплює")
if "Яке саме замовлення оплачено?" not in _chat: fails.append("коли замовлень кілька — питаємо, яке саме, кнопками")
if "звірить надходження" not in _chat: fails.append("бот не вдає, що бачить оплату: каже, що перевірить людина")

for f in fails: print("  -", f)

import sys
total = len(CASES) + 16 + 20 + 9 + 4 + 32
print(f"\nFAQ: {total - len(fails)}/{total}")
print(f"{'ПРОВАЛЕНО: '+str(len(fails)) if fails else 'усе витримано'}")

