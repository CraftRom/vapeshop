# Присвійні звороти: ознака, що питання про конкретну людину, а не про
# правила магазину. Українською й російською, бо групи двомовні.
# Пишемо обидві абетки явно: normalize() не зводить «є» до «е», тож
# український варіант треба перелічити окремо від російського — інакше
# «моє замовлення» пройшло б повз фільтр.
PERSONAL_MARKERS = (
    "моє", "мое", "мій", "мий", "моя", "мою", "мої", "мои",
    "мого", "моєму", "моему", "моїм", "моим", "моїх", "моих",
    "у мене", "в мене", "у меня", "мені", "мени", "мне", "меня",
    "замовляв", "замовила", "заказал", "заказыв", "купував", "купила",
)


def _is_personal(normalized: str) -> bool:
    """Чи стосується питання конкретного клієнта."""
    return any(marker in normalized for marker in PERSONAL_MARKERS)


def match(text: str, shop=None, public: bool = False) -> Rule | None:
    """Знаходить правило для повідомлення. None — якщо впевненості немає.

    public=True — розмова в групі чи каналі: беремо лише ті правила, чия
    відповідь нікого не викриває.
    """
    normalized = normalize(text)
    if len(normalized.strip()) < 2:
        return None

    # У публічному чаті питання про своє — привід замовкнути, а не відповісти.
    #
    # Без цієї перевірки «де моє замовлення» збігалося б із загальним
    # правилом «як оформити замовлення» — за ключовими словами «де» і
    # «замов». Формально не витік, але людина отримує інструкцію замість
    # відповіді, ще й перед усією групою. Персональні питання належать
    # приватному чату цілком.
    if public and _is_personal(normalized):
        return None

    for rule in RULES:
        if public and not rule.public:
            continue
        if rule.needs == "bonus" and shop is not None and not shop.bonus_enabled:
            continue
        if rule.needs == "referral" and shop is not None and not (
            shop.referral_enabled and shop.bonus_enabled
        ):
            continue
        if all(_has(normalized, group) for group in rule.groups):
            return rule
    return None


def render(rule: Rule, shop=None, public: bool = False) -> str:
    """Підставляє в відповідь дані магазину.

    public=True — беремо стислий варіант, якщо він заданий.
    """
    body = rule.public_answer if (public and rule.public_answer) else rule.answer
    return body.format(
        age=getattr(shop, "min_age", 18),
        bonus_max=_num(getattr(shop, "bonus_max_percent", Decimal(30))),
        referral=_num(getattr(shop, "referral_percent", Decimal(5))),
        currency=getattr(shop, "currency", "грн"),
    )


def _num(value) -> str:
    return f"{Decimal(str(value)):.0f}"
