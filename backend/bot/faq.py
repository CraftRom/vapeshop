"""Розпізнавання типових питань і відповіді на них.

Навіщо. Більшість повідомлень у магазин — це кілька повторюваних питань:
як замовити, скільки коштує доставка, чи можна повернути. Менеджер
відповідає на них десятки разів на день, а клієнт чекає. Бот відповідає
миттєво й цілодобово, а менеджеру лишається те, що справді потребує людини.

Як влаштовано. Не машинне навчання, а зіставлення за ключовими словами:
на такому обсязі це передбачувано, налагоджується й не вигадує фактів.
Кожне правило описує групи слів, з яких хоча б одне має збігтися. Правила
перевіряються по порядку, спрацьовує перше — тож конкретніші стоять вище.

Межа. Якщо впевненого збігу немає, бот мовчить і передає повідомлення
менеджеру. Помилкова відповідь гірша за її відсутність: клієнт отримає не
те, що питав, і ще й вирішить, що з ним говорить автовідповідач.
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from decimal import Decimal
from datetime import datetime, timedelta, timezone

# Літери, які люди плутають між українською й російською розкладками.
# Без нормалізації «як замовити» і «как заказать» довелося б описувати двічі.
# «ъ» і «ё» тут стояли двічі: словник мовчки лишав останній запис, тож
# на роботу це не впливало, але кожен повтор виглядав як окреме правило.
_FOLD = str.maketrans({
    "ё": "е", "ъ": "", "ы": "и", "э": "е",
    "ї": "і",
})


def normalize(text: str) -> str:
    """Приводить повідомлення до вигляду, зручного для порівняння."""
    lowered = unicodedata.normalize("NFKC", (text or "").lower())
    lowered = lowered.translate(_FOLD)
    # Розділові знаки й емодзі на пробіли: «Як замовити??» має збігтися
    return " " + re.sub(r"[^\w\u0400-\u04ff]+", " ", lowered).strip() + " "


def _has(text: str, words: tuple[str, ...], fuzzy: bool = False) -> bool:
    """Чи є в тексті хоч одне зі слів. Порівнюємо за початком слова.

    Початок, а не точний збіг: «замовити», «замовлення», «замовляти» —
    одне й те саме питання, а перелічувати всі форми української мови
    в списку ключових слів марно.

    fuzzy=True вмикає допуск на одну описку. Вмикається лише другим
    проходом — див. match().
    """
    if any(re.search(rf"\s{re.escape(w)}", text) for w in words):
        return True
    return _has_typo(text, words) if fuzzy else False


def _has_typo(text: str, words: tuple[str, ...]) -> bool:
    """Те саме, але з допуском на одну помилку в довгих словах.

    У чаті пишуть з телефона й поспіхом: «замвити», «доствка», «пирдбати».
    Точний збіг такі повідомлення проґавлює, і бот виглядає тупим саме там,
    де відповідь очевидна людині.

    Поріг у пʼять символів навмисний: у коротких словах одна помилка робить
    з «де» — «те», а з «як» — «як би», і допуск почав би ловити випадкове.
    """
    tokens = [t for t in text.split() if len(t) >= 5]
    if not tokens:
        return False
    for word in words:
        if len(word) < 5:
            continue
        for token in tokens:
            # Ключі — це основи, тож порівнюємо початок токена. Довжину
            # беремо трьох варіантів: пропущена буква вкорочує слово,
            # зайва — подовжує. Без цього «замвити» (загублена «о») не
            # збіглося б із основою «замов»: на однаковій довжині різниця
            # виходить у дві правки, хоч помилка одна.
            for size in (len(word) - 1, len(word), len(word) + 1):
                if size < 3:
                    continue
                if _close(token[:size], word):
                    return True
    return False


def _close(token_head: str, key: str) -> bool:
    """Чи відрізняється початок слова від основи не більше ніж на одну правку.

    Не будь-яку правку. Заміна першої або останньої літери основи заборонена,
    бо саме вона перетворює одне слово на інше: «поставив» — не «доставка»,
    «оплакую» — не «оплата». Пропущена ж або зайва літера всередині — це
    майже завжди друкарська помилка: «замвити», «доствка», «оплтити».
    """
    if token_head == key:
        return True
    if abs(len(token_head) - len(key)) > 1:
        return False

    if len(token_head) == len(key):
        diffs = [i for i, (x, y) in enumerate(zip(token_head, key)) if x != y]
        if len(diffs) != 1:
            return False
        position = diffs[0]
        return 0 < position < len(key) - 1

    # Різна довжина — вставка або видалення. Перевіряємо, що решта збігається.
    shorter, longer = (token_head, key) if len(token_head) < len(key) else (key, token_head)
    for skip in range(len(longer)):
        if longer[:skip] + longer[skip + 1:] == shorter:
            # Ні на початку, ні в кінці. Пропуск останньої літери основи —
            # це не описка, а просто коротший префікс: за ним «оплакую»
            # зійшлося б з «оплат», бо «опла» — початок обох слів.
            return 0 < skip < len(longer) - 1
    return False


@dataclass
class Rule:
    key: str
    # Спрацьовує, якщо збіглася хоч одна група з кожного набору.
    # Два набори означають «і те, і те»: «як» + «замовити».
    groups: tuple[tuple[str, ...], ...]
    answer: str
    # Показувати кнопку магазину під відповіддю
    with_shop: bool = False
    # Правило вимкнене, якщо відповідний модуль магазину вимкнений
    needs: str = ""
    # Чи можна відповідати цим правилом у групі або каналі.
    #
    # За замовчуванням — ні. У публічному чаті відповідь бачать усі, тож
    # доречні лише загальні пояснення про магазин. Усе, що стосується
    # конкретної людини — її замовлення, бонуси, реферальне посилання —
    # лишається в особистому листуванні.
    public: bool = False
    # Коротший варіант відповіді для групи. Порожньо — беремо звичайний.
    #
    # У приватному чаті доречно розписати кроки: людина читає сама й нікому
    # не заважає. У групі та сама відповідь на пів екрана виглядає як спам,
    # навіть коли вона доречна. Тому загальні правила мають стислу форму.
    public_answer: str = ""
    # Чи допускати описку в ключах цього правила.
    #
    # Для привітань і подяк — ні. Це короткі слова з купою сусідів на одну
    # правку: «приват» відрізняється від «привіт» однією літерою, і банк
    # у розмові перетворювався б на привітання. Там, де ключ несе зміст
    # («доставка», «оплата»), така плутанина неможлива.
    fuzzy: bool = True


@dataclass(frozen=True)
class MatchCandidate:
    """Один можливий намір із пояснюваними доказами.

    Це не ML-score і не ймовірність. Число потрібне лише для порівняння
    правил між собою: конкретний термін на кшталт ``промокод`` має бути
    сильнішим за службове ``як`` + побічне ``замовляю``.
    """

    rule: Rule
    score: float
    strong_score: float
    matched_terms: tuple[str, ...]
    strong_terms: tuple[str, ...]
    fuzzy_hits: int = 0


@dataclass(frozen=True)
class MatchDecision:
    """Рішення маршрутизатора FAQ. ``rule=None`` означає: мовчати.

    ``reason`` навмисно машинний і без тексту клієнта — його можна безпечно
    писати в технічний лог та використовувати в QA, не накопичуючи PII.
    """

    rule: Rule | None
    reason: str
    confidence: float = 0.0
    candidates: tuple[MatchCandidate, ...] = ()


@dataclass(frozen=True)
class ConversationContext:
    """Контекст, який може заборонити автоматичну репліку.

    ``human_active`` — менеджер уже веде цю розмову. ``recent_auto_keys`` —
    теми, які бот щойно пояснював у цій самій сесії; повторювати ту саму
    довідку замість передачі людині не треба.
    """

    human_active: bool = False
    recent_auto_keys: tuple[str, ...] = ()



