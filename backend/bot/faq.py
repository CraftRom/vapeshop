def payment_claim(text: str) -> bool:
    """Чи каже людина, що вже оплатила.

    Навіщо окремо від правил. «Оплачено» збігалося з правилом про оплату
    за коренем «оплат» — і бот у відповідь пояснював, ЯК платити. Людина
    щойно переказала гроші, а їй розповідають про накладений платіж. На
    знімку саме це: «Оплачено» → довідка про способи оплати, і жодного
    натяку, що повідомлення кудись передали.

    Розрізняє не тема, а форма дієслова: «оплатив», «скинув», «переказав»
    — доконаний вид, тобто дія вже сталася. Питальне слово поруч скасовує
    здогад: «як оплатити», «куди скинути гроші» — це все ще питання, і
    відповідати на нього має довідка.

    Помилитись тут дешевше в один бік: якщо ми приймемо питання за
    повідомлення про оплату, менеджер прочитає зайве. Якщо навпаки —
    людина отримає інструкцію замість підтвердження і піде писати ще раз.
    """
    normalized = normalize(text)
    if "?" in (text or ""):
        return False
    if not _has(normalized, PAID_WORDS):
        return False
    # «Чекаю доставку» — не про оплату.
    #
    # Коротке «чек» збігалося за початком слова з «чекати», і людина, яка
    # питає, коли прийде посилка, отримувала відповідь про переказ. Тому
    # чек як іменник розпізнаємо лише в сполученнях («чек надіслав», «ось
    # чек»), а решту цих слів звіряємо як є.
    if _has(normalized, ("чека", "чекат", "чекаю", "жду", "ждат")):
        return False
    # Питальні слова звіряємо цілими, а не за початком, як решту ключів.
    # «Де» за початком слова збігається з «деньги», і «деньги отправил»
    # ставало питанням. Для коротких службових слів початок — надто
    # слабка ознака.
    return not any(re.search(rf"\s{re.escape(w)}\s", normalized)
                   for w in ASKING_WORDS)


