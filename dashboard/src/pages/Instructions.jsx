export default function Instructions() {
  const admin = isAdmin()
  const visible = GUIDES.filter((g) => !g.adminOnly || admin)
  const [open, setOpen] = useState(visible[0]?.key)

  return (
    <>
      <div className="page-head">
        <div>
          <h1>Інструкції</h1>
          <p>
            Як користуватися панеллю. Версія {APP_VERSION}
            {admin ? ' · показано всі розділи' : ' · показано доступні вам розділи'}
          </p>
        </div>
      </div>

      <div className="rail" style={{ marginBottom: 16 }}>
        {visible.map((g) => (
          <button
            key={g.key}
            className={`btn small ${open === g.key ? '' : 'ghost'}`}
            onClick={() => setOpen(g.key)}
          >
            {g.title}
          </button>
        ))}
      </div>

      {visible
        .filter((g) => g.key === open)
        .map((g) => (
          <div className="card" key={g.key}>
            <h2 style={{ marginTop: 0 }}>{g.title}</h2>
            <p className="faint" style={{ marginTop: -6 }}>{g.lead}</p>

            {g.blocks.map((b) => (
              <div key={b.h} style={{ marginTop: 16 }}>
                <h3 style={{ margin: '0 0 4px', fontSize: 15 }}>{b.h}</h3>
                <p style={{ margin: 0, lineHeight: 1.55 }}>{b.p}</p>
              </div>
            ))}
          </div>
        ))}

      <p className="faint" style={{ marginTop: 16 }}>
        Не знайшли відповіді — запитайте адміністратора. Якщо питання
        повторюється у кількох людей, його варто додати сюди.
      </p>
    </>
  )
}
