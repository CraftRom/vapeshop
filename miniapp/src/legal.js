/** Підставляє реквізити й прибирає порожні місця.
 *
 *  Не всі реквізити обовʼязкові. ФОП без пошти або без коду в реєстрі —
 *  звичайна річ, і оферта від цього не втрачає сили: закон вимагає, щоб
 *  покупець міг ідентифікувати продавця й звʼязатися з ним. Назви,
 *  адреси й телефону для цього досить.
 *
 *  Раніше незаповнене поле показувалося клієнту як «{{SELLER_CODE}}»
 *  просто в тексті договору. Це гірше за відсутність реквізиту: виглядає
 *  як зламаний сайт і підриває довіру саме там, де вона потрібна.
 */
function fill(text, seller) {
  // Спершу умовні шматки: {{?KEY}}текст{{/KEY}} лишається тільки коли
  // значення заповнене. Це чесніше за вирізання розділових знаків —
  // фразу «напишіть на пошту або менеджеру» не можна залатати регуляркою,
  // її треба або лишити цілою, або прибрати цілком.
  let out = text.replace(
    /\{\{\?(\w+)\}\}([\s\S]*?)\{\{\/\1\}\}/g,
    (_, key, body) => (seller?.[key] && String(seller[key]).trim() ? body : ''),
  )

  out = out.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    const value = seller?.[key]
    return value ? String(value).trim() : ''
  })

  // Прибираємо сліди від порожніх підстановок: коми, крапки з комою й
  // роздільники, що лишились без свого значення.
  out = out
    .replace(/,\s*,/g, ',')
    .replace(/,\s*\./g, '.')
    .replace(/·\s*·/g, '·')
    // Роздільник, що лишився після двокрапки або на початку рядка, —
    // найпомітніший слід вирізаного значення: «Звʼязок: · +380».
    .replace(/:\s*[·,]\s*/g, ': ')
    .replace(/(^|\n)[ \t]*[·,]\s*/g, '$1')
    .replace(/\s*[·,]\s*(\n|$)/g, '$1')
    .replace(/\(\s*\)/g, '')
    .replace(/[ \t]{2,}/g, ' ')
    // Рядок, від якого лишилися самі розділові знаки, прибираємо цілком
    .replace(/(^|\n)[ \t]*[·,.;:—-]+[ \t]*(?=\n|$)/g, '$1')
    // Три й більше порожніх рядки поспіль — теж слід від вирізаного
    .replace(/\n{3,}/g, '\n\n')

  return out.trim()
}

/** Чи вистачає реквізитів, щоб документи мали сенс.
 *
 *  Мінімум — назва, адреса й спосіб звʼязку. Без них оферта не
 *  ідентифікує продавця, і показувати її як чинний договір не можна.
 */
export function sellerIsUsable(seller) {
  const has = (key) => Boolean(seller?.[key] && String(seller[key]).trim())
  return has('SELLER_NAME') && has('SELLER_ADDRESS') &&
    (has('SELLER_PHONE') || has('SELLER_EMAIL'))
}

