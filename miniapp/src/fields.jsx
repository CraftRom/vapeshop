/** Поле введення, у яке React не пише під час набору.
 *
 * Сьома спроба, і цього разу причина виміряна, а не вгадана.
 *
 * Діагностика на живому телефоні показала, що з кольорами все гаразд:
 * білий текст на темній підкладці, непрозорість одиниця, жодних чужих
 * приписів і жодної сторонньої таблиці стилів. Але вирішальним було
 * інше — у самій діагностиці пробне поле показувало набране нормально.
 * Різниця між ним і полями форми рівно одна: пробне поле некероване, а
 * поля форми керовані React.
 *
 * Звідси й поломка. Керованому полю React присвоює `value` на кожному
 * перемальовуванні. Клавіатура Android набирає слово «композицією» —
 * незавершеним фрагментом, який належить самій клавіатурі. Присвоєння
 * `value` посеред композиції її скидає, і WebView лишається без тексту
 * для показу: значення в елементі є, каретка рухається, гліфів немає.
 * Слово видно в смужці підказок клавіатури — саме там воно тоді й
 * живе. Щойно фокус іде геть, композиція завершується, React малює
 * значення звичайним чином — і текст «зʼявляється» в сусідньому полі.
 *
 * Тому тут поле некероване: значення живе в DOM, а назовні йде через
 * onValue. React пише в елемент лише тоді, коли значення змінили
 * ззовні — вибрали місто зі списку, підставили префікс телефона,
 * скинули форму після замовлення. Своє ж значення назад не повертаємо
 * ніколи: саме це повернення й ламало набір.
 */
import { useEffect, useRef } from 'react'

export function TextInput({ value = '', onValue, multiline = false, ...rest }) {
  const node = useRef(null)
  // Останнє значення, яке ми самі віддали назовні. Усе, що приходить
  // згори й від нього відрізняється, — зміна ззовні.
  const mine = useRef(value)

  useEffect(() => {
    const el = node.current
    if (!el) return
    if (value === mine.current) return
    mine.current = value
    if (el.value !== value) el.value = value
  }, [value])

  const report = (event) => {
    mine.current = event.target.value
    onValue(event.target.value)
  }

  const Tag = multiline ? 'textarea' : 'input'
  return <Tag ref={node} defaultValue={value} onChange={report} {...rest} />
}
