import fs from 'node:fs'
import assert from 'node:assert/strict'
const read = path => fs.readFileSync(new URL(path, import.meta.url), 'utf8')
const mini = read('../src/screens/Chat.jsx')
const dash = read('../../dashboard/src/components/ChatAttachment.jsx')
const order = read('../../dashboard/src/pages/OrderPage.jsx')
const support = read('../../dashboard/src/pages/Support.jsx')
const api = read('../../dashboard/src/api.js')
const shop = read('../../backend/api/routers/shop.py')
const shopSupport = read('../../backend/api/routers/shop_support.py')
const staffOrder = read('../../backend/api/routers/orders.py')
const staffSupport = read('../../backend/api/routers/support.py')
const media = read('../../backend/api/chat_media.py')
const security = read('../../backend/api/security_middleware.py')
const nginx = read('../../deploy/nginx/app.conf.template')
let total = 0
function check(value, label) { assert.ok(value, label); total++ }
check(mini.includes('application/pdf,.pdf'), 'PDF file selector in both MiniApp conversations')
check(mini.includes('const pdf = file.type') && mini.includes('PDF має бути до 15 МБ'), 'client-side PDF validation')
check(mini.includes('chatMedia(order.id, file, support)'), 'both customer upload routes')
check(mini.includes('isPdf') && mini.includes('Переглянути PDF') && mini.includes('Завантажити PDF'), 'client preview and download')
check(dash.includes('Переглянути PDF') && dash.includes('Завантажити PDF'), 'staff preview and download')
check(mini.includes('sandbox="allow-scripts"') && dash.includes('sandbox="allow-scripts"') && !mini.includes('allow-same-origin'), 'PDF preview sandboxed from shop origin')
check(mini.includes('URL.revokeObjectURL') && dash.includes('URL.revokeObjectURL'), 'free attachment URLs')
check(order.includes('api.orders.sendPdf(orderId, file)') && support.includes('api.support.sendPdf(thread.id, file)'), 'staff can send PDFs both chats')
check(api.includes('sendPdf: (id, file) => uploadChatPdf') && api.includes('authorizedFetch('), 'staff upload uses CSRF/cookie authenticated transport')
check(shop.includes('send_media_to_staff') && shopSupport.includes('send_media_to_staff'), 'Mini App PDF routes use existing private Telegram path')
check(staffOrder.includes('async def send_pdf(') && staffSupport.includes('async def send_pdf('), 'staff write endpoints')
check(media.includes('send_pdf_to_client') && media.includes('send_document') && media.includes('pdf_signature'), 'server validates signature and calls Telegram sendDocument')
check(media.includes("'Content-Disposition'") && media.includes('attachment; filename*='), 'never inline-serve PDF in API origin')
check(security.includes('support/threads/[0-9]+/media') && security.includes('orders/[0-9]+/chat/(photo|media)') && security.includes('limit = 18 * 1024 * 1024'), 'signed miniapp media and bounded multipart inputs')
check(nginx.includes('messages/pdf') && nginx.includes('frame-src \'self\' blob:') && nginx.includes('client_max_body_size 18M'), 'Nginx PDF permissions and upload sizes')
console.log(`CHAT PDF: ${total}/${total}`)
